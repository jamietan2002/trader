"""Structured Strategy Configuration Models, Rule Engine, and Persistent Strategy Registry.

Enforces:
- Machine-readable strategy configurations (no free-form natural language execution).
- Full versioned lifecycle: DRAFT -> BACKTESTING -> VALIDATION -> PAPER_TRADING -> APPROVED_FOR_REVIEW -> REJECTED -> RETIRED.
- Immutability of strategies currently in PAPER_TRADING.
- All 5 Strategy Families:
  1. Momentum / Trend Following (`MOMENTUM_TREND`)
  2. Post-Earnings Announcement Drift (`PEAD`)
  3. Breakout Trading (`BREAKOUT`)
  4. Mean Reversion (`MEAN_REVERSION`)
  5. Sector Rotation / Relative Strength (`SECTOR_ROTATION`)
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field, asdict
from enum import Enum
from typing import Any, Dict, List, Optional, Sequence

from core.indicators.technical import IndicatorSnapshot
from core.market_data.models import EarningsEvent
from infrastructure.database.db import DatabaseManager, utc_now_iso


class StrategyFamily(str, Enum):
    MOMENTUM_TREND = "MOMENTUM_TREND"
    PEAD = "PEAD"
    BREAKOUT = "BREAKOUT"
    MEAN_REVERSION = "MEAN_REVERSION"
    SECTOR_ROTATION = "SECTOR_ROTATION"


class StrategyStatus(str, Enum):
    DRAFT = "DRAFT"
    BACKTESTING = "BACKTESTING"
    VALIDATION = "VALIDATION"
    PAPER_TRADING = "PAPER_TRADING"
    APPROVED_FOR_REVIEW = "APPROVED_FOR_REVIEW"
    REJECTED = "REJECTED"
    RETIRED = "RETIRED"


@dataclass(frozen=True)
class StrategyConfig:
    """Machine-readable, deterministic strategy specification."""

    strategy_id: str
    version: int
    name: str
    strategy_family: str  # StrategyFamily value
    status: str  # StrategyStatus value
    hypothesis: str
    observable_phenomenon: str
    invalidation_conditions: str
    target_market_regimes: List[str]
    holding_period_min_days: int
    holding_period_max_days: int
    universe: List[str]
    required_indicators: List[str]
    entry_rules: Dict[str, Any]
    exit_rules: Dict[str, Any]
    risk_params: Dict[str, Any]
    created_at: str = field(default_factory=utc_now_iso)
    updated_at: str = field(default_factory=utc_now_iso)
    dataset_version: Optional[str] = None
    backtest_summary: Optional[Dict[str, Any]] = None
    validation_summary: Optional[Dict[str, Any]] = None
    promotion_decision_reason: Optional[str] = None

    def __post_init__(self) -> None:
        if self.strategy_family not in {f.value for f in StrategyFamily}:
            raise ValueError(f"Unsupported strategy_family: {self.strategy_family}")
        if self.status not in {s.value for s in StrategyStatus}:
            raise ValueError(f"Unsupported strategy status: {self.status}")
        if not isinstance(self.entry_rules, dict) or not self.entry_rules:
            raise ValueError("entry_rules must be a non-empty structured dictionary")
        if not isinstance(self.exit_rules, dict) or not self.exit_rules:
            raise ValueError("exit_rules must be a non-empty structured dictionary")
        if self.holding_period_min_days < 1 or self.holding_period_max_days < self.holding_period_min_days:
            raise ValueError("Invalid holding period range")

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass(frozen=True)
class TradeSignal:
    """Deterministic entry or exit signal generated by the StrategySignalEngine."""

    strategy_id: str
    strategy_version: int
    strategy_family: str
    ticker: str
    signal_date: str
    action: str  # ENTRY_LONG | EXIT_LONG
    reason: str
    conviction_score: float  # Deterministic rule score [0.0, 1.0]
    atr_at_signal: float
    close_at_signal: float
    stop_loss_price: Optional[float] = None
    take_profit_price: Optional[float] = None


class StrategySignalEngine:
    """Deterministic rule evaluation engine for all supported strategy families."""

    @staticmethod
    def evaluate_entry(
        config: StrategyConfig,
        ind: IndicatorSnapshot,
        spy_ind: Optional[IndicatorSnapshot],
        recent_earnings: Sequence[EarningsEvent],
        sector_rs_rank: Optional[int] = None,
    ) -> Optional[TradeSignal]:
        rules = config.entry_rules
        exits = config.exit_rules
        family = config.strategy_family

        if ind.atr_14 is None or ind.atr_14 <= 0 or ind.close <= 0:
            return None

        # Optional SPY market regime filter (e.g., require SPY > SMA50 or realized vol cap)
        if rules.get("require_spy_above_sma50", False) and spy_ind is not None:
            if spy_ind.sma_50 is not None and spy_ind.close < spy_ind.sma_50:
                return None
        max_spy_vol = rules.get("max_spy_realised_vol_20d")
        if max_spy_vol is not None and spy_ind is not None and spy_ind.realised_vol_20d_annualised is not None:
            if spy_ind.realised_vol_20d_annualised > float(max_spy_vol):
                return None

        stop_atr_mult = float(exits.get("stop_loss_atr_mult", 2.0))
        tp_atr_mult = float(exits.get("take_profit_atr_mult", 3.5))
        stop_price = round(max(0.01, ind.close - stop_atr_mult * ind.atr_14), 2)
        tp_price = round(ind.close + tp_atr_mult * ind.atr_14, 2)

        if family == StrategyFamily.MOMENTUM_TREND.value:
            if ind.sma_20 is None or ind.sma_50 is None or ind.rsi_14 is None:
                return None
            if ind.rs_vs_spy_20d is None or ind.volume_ratio_20 is None or ind.ret_20d_pct is None:
                return None

            min_rs = float(rules.get("min_rs_vs_spy_20d", 2.0))
            min_ret_20d = float(rules.get("min_ret_20d_pct", 3.0))
            min_vol_ratio = float(rules.get("min_volume_ratio_20", 1.05))
            min_rsi = float(rules.get("min_rsi_14", 52.0))
            max_rsi = float(rules.get("max_rsi_14", 78.0))

            trend_aligned = ind.close > ind.sma_20 > ind.sma_50
            rs_ok = ind.rs_vs_spy_20d >= min_rs
            mom_ok = ind.ret_20d_pct >= min_ret_20d
            vol_ok = ind.volume_ratio_20 >= min_vol_ratio
            rsi_ok = min_rsi <= ind.rsi_14 <= max_rsi

            if trend_aligned and rs_ok and mom_ok and vol_ok and rsi_ok:
                score = min(1.0, 0.55 + (ind.rs_vs_spy_20d / 30.0) + (ind.volume_ratio_20 - 1.0) * 0.15)
                return TradeSignal(
                    strategy_id=config.strategy_id,
                    strategy_version=config.version,
                    strategy_family=family,
                    ticker=ind.ticker,
                    signal_date=ind.bar_date,
                    action="ENTRY_LONG",
                    reason=(
                        f"Momentum Trend: Close ${ind.close:.2f} > SMA20 > SMA50, "
                        f"RS20d={ind.rs_vs_spy_20d:+.2f}%, VolRatio={ind.volume_ratio_20:.2f}x, RSI={ind.rsi_14:.1f}"
                    ),
                    conviction_score=round(score, 3),
                    atr_at_signal=ind.atr_14,
                    close_at_signal=ind.close,
                    stop_loss_price=stop_price,
                    take_profit_price=tp_price,
                )

        elif family == StrategyFamily.PEAD.value:
            if not recent_earnings or ind.volume_ratio_20 is None or ind.ret_1d_pct is None:
                return None
            latest_ev = recent_earnings[0]
            min_eps_surprise = float(rules.get("min_eps_surprise_pct", 5.0))
            min_rev_growth = float(rules.get("min_revenue_growth_yoy_pct", 8.0))
            min_guidance = float(rules.get("min_guidance_delta_pct", 0.0))
            min_vol_ratio = float(rules.get("min_volume_ratio_20", 1.40))
            max_days_since_report = int(rules.get("max_days_since_earnings", 5))

            from datetime import date as dt_date
            days_elapsed = (dt_date.fromisoformat(ind.bar_date) - dt_date.fromisoformat(latest_ev.report_date)).days
            if days_elapsed < 0 or days_elapsed > max_days_since_report:
                return None

            if (
                latest_ev.eps_surprise_pct >= min_eps_surprise
                and latest_ev.revenue_growth_yoy_pct >= min_rev_growth
                and latest_ev.guidance_delta_pct >= min_guidance
                and ind.volume_ratio_20 >= min_vol_ratio
                and (ind.sma_50 is None or ind.close >= ind.sma_50 * 0.98)
            ):
                score = min(1.0, 0.60 + (latest_ev.eps_surprise_pct / 45.0))
                return TradeSignal(
                    strategy_id=config.strategy_id,
                    strategy_version=config.version,
                    strategy_family=family,
                    ticker=ind.ticker,
                    signal_date=ind.bar_date,
                    action="ENTRY_LONG",
                    reason=(
                        f"PEAD Catalyst ({latest_ev.report_date} {latest_ev.announcement_session}): "
                        f"EPS Surprise {latest_ev.eps_surprise_pct:+.1f}%, Rev YoY {latest_ev.revenue_growth_yoy_pct:+.1f}%, "
                        f"Guidance {latest_ev.guidance_delta_pct:+.1f}%, VolRatio={ind.volume_ratio_20:.2f}x"
                    ),
                    conviction_score=round(score, 3),
                    atr_at_signal=ind.atr_14,
                    close_at_signal=ind.close,
                    stop_loss_price=stop_price,
                    take_profit_price=tp_price,
                )

        elif family == StrategyFamily.BREAKOUT.value:
            if ind.high_20d_prior is None or ind.volume_ratio_20 is None:
                return None
            min_vol_ratio = float(rules.get("min_volume_ratio_20", 1.35))
            max_consol_range = float(rules.get("max_consolidation_range_10d_pct", 12.0))
            require_above_sma50 = bool(rules.get("require_above_sma50", True))

            broke_20d_high = ind.close > ind.high_20d_prior
            vol_expanded = ind.volume_ratio_20 >= min_vol_ratio
            consol_ok = (
                ind.consolidation_range_10d_pct is None
                or ind.consolidation_range_10d_pct <= max_consol_range
            )
            sma50_ok = not require_above_sma50 or (ind.sma_50 is not None and ind.close > ind.sma_50)

            if broke_20d_high and vol_expanded and consol_ok and sma50_ok:
                near_52w = (
                    ind.high_252d_prior is not None and ind.close >= ind.high_252d_prior * 0.97
                )
                score = min(1.0, 0.58 + (ind.volume_ratio_20 - 1.0) * 0.18 + (0.08 if near_52w else 0.0))
                return TradeSignal(
                    strategy_id=config.strategy_id,
                    strategy_version=config.version,
                    strategy_family=family,
                    ticker=ind.ticker,
                    signal_date=ind.bar_date,
                    action="ENTRY_LONG",
                    reason=(
                        f"20d High Breakout: Close ${ind.close:.2f} > 20dHigh ${ind.high_20d_prior:.2f}, "
                        f"VolExpansion={ind.volume_ratio_20:.2f}x, 10dRange={ind.consolidation_range_10d_pct or 0.0:.1f}%"
                    ),
                    conviction_score=round(score, 3),
                    atr_at_signal=ind.atr_14,
                    close_at_signal=ind.close,
                    stop_loss_price=stop_price,
                    take_profit_price=tp_price,
                )

        elif family == StrategyFamily.MEAN_REVERSION.value:
            if ind.rsi_14 is None or ind.bb_lower_20 is None or ind.sma_200 is None:
                return None
            max_rsi = float(rules.get("max_rsi_14", 34.0))
            require_uptrend_200 = bool(rules.get("require_above_sma200", True))
            uptrend_ok = not require_uptrend_200 or (ind.close > ind.sma_200 * 0.95)
            below_bb = ind.close <= ind.bb_lower_20 * 1.01

            if ind.rsi_14 <= max_rsi and below_bb and uptrend_ok:
                score = min(1.0, 0.55 + (max_rsi - ind.rsi_14) / 40.0)
                return TradeSignal(
                    strategy_id=config.strategy_id,
                    strategy_version=config.version,
                    strategy_family=family,
                    ticker=ind.ticker,
                    signal_date=ind.bar_date,
                    action="ENTRY_LONG",
                    reason=(
                        f"Mean Reversion Oversold: RSI={ind.rsi_14:.1f} <= {max_rsi}, "
                        f"Close ${ind.close:.2f} near LowerBB ${ind.bb_lower_20:.2f}"
                    ),
                    conviction_score=round(score, 3),
                    atr_at_signal=ind.atr_14,
                    close_at_signal=ind.close,
                    stop_loss_price=stop_price,
                    take_profit_price=tp_price,
                )

        elif family == StrategyFamily.SECTOR_ROTATION.value:
            if ind.rs_vs_spy_20d is None or ind.sma_20 is None or ind.sma_50 is None:
                return None
            max_sector_rank = int(rules.get("max_sector_rank", 2))
            min_stock_rs = float(rules.get("min_rs_vs_spy_20d", 3.5))
            if (
                (sector_rs_rank is None or sector_rs_rank <= max_sector_rank)
                and ind.rs_vs_spy_20d >= min_stock_rs
                and ind.close > ind.sma_20 > ind.sma_50
            ):
                score = min(1.0, 0.60 + ind.rs_vs_spy_20d / 35.0)
                return TradeSignal(
                    strategy_id=config.strategy_id,
                    strategy_version=config.version,
                    strategy_family=family,
                    ticker=ind.ticker,
                    signal_date=ind.bar_date,
                    action="ENTRY_LONG",
                    reason=(
                        f"Sector Rotation Leader: SectorRank={sector_rs_rank or 1}, "
                        f"Stock RS20d={ind.rs_vs_spy_20d:+.2f}%"
                    ),
                    conviction_score=round(score, 3),
                    atr_at_signal=ind.atr_14,
                    close_at_signal=ind.close,
                    stop_loss_price=stop_price,
                    take_profit_price=tp_price,
                )

        return None

    @staticmethod
    def evaluate_exit(
        config: StrategyConfig,
        ind: IndicatorSnapshot,
        entry_price: float,
        highest_price_since_entry: float,
        holding_days: int,
        stop_loss_price: Optional[float],
        take_profit_price: Optional[float],
    ) -> Optional[TradeSignal]:
        exits = config.exit_rules
        atr = ind.atr_14 or (ind.close * 0.02)

        # 1. Hard stop-loss check (can trigger intraday via low or close)
        if stop_loss_price is not None and ind.low <= stop_loss_price:
            return TradeSignal(
                strategy_id=config.strategy_id,
                strategy_version=config.version,
                strategy_family=config.strategy_family,
                ticker=ind.ticker,
                signal_date=ind.bar_date,
                action="EXIT_LONG",
                reason=f"Stop-Loss triggered at ${stop_loss_price:.2f} (Bar Low=${ind.low:.2f})",
                conviction_score=1.0,
                atr_at_signal=atr,
                close_at_signal=stop_loss_price,
            )

        # 2. Volatility-adjusted trailing stop check
        trailing_atr_mult = exits.get("trailing_stop_atr_mult")
        if trailing_atr_mult is not None and holding_days >= config.holding_period_min_days:
            trail_stop = highest_price_since_entry - float(trailing_atr_mult) * atr
            if ind.close <= trail_stop:
                return TradeSignal(
                    strategy_id=config.strategy_id,
                    strategy_version=config.version,
                    strategy_family=config.strategy_family,
                    ticker=ind.ticker,
                    signal_date=ind.bar_date,
                    action="EXIT_LONG",
                    reason=f"ATR Trailing Stop triggered at ${ind.close:.2f} (Peak=${highest_price_since_entry:.2f})",
                    conviction_score=1.0,
                    atr_at_signal=atr,
                    close_at_signal=ind.close,
                )

        # 3. Take-profit target check (after minimum holding period or intraday high)
        if (
            take_profit_price is not None
            and holding_days >= config.holding_period_min_days
            and ind.high >= take_profit_price
        ):
            return TradeSignal(
                strategy_id=config.strategy_id,
                strategy_version=config.version,
                strategy_family=config.strategy_family,
                ticker=ind.ticker,
                signal_date=ind.bar_date,
                action="EXIT_LONG",
                reason=f"Take-Profit target reached at ${take_profit_price:.2f}",
                conviction_score=1.0,
                atr_at_signal=atr,
                close_at_signal=take_profit_price,
            )

        # 4. Trend / Mean-Reversion indicator exit rules (only after holding_period_min_days)
        if holding_days >= config.holding_period_min_days:
            if exits.get("exit_below_sma20", False) and ind.sma_20 is not None and ind.close < ind.sma_20:
                return TradeSignal(
                    strategy_id=config.strategy_id,
                    strategy_version=config.version,
                    strategy_family=config.strategy_family,
                    ticker=ind.ticker,
                    signal_date=ind.bar_date,
                    action="EXIT_LONG",
                    reason=f"Trend exit: Close ${ind.close:.2f} crossed below SMA20 ${ind.sma_20:.2f}",
                    conviction_score=0.9,
                    atr_at_signal=atr,
                    close_at_signal=ind.close,
                )
            rsi_exit = exits.get("exit_rsi_above")
            if rsi_exit is not None and ind.rsi_14 is not None and ind.rsi_14 >= float(rsi_exit):
                return TradeSignal(
                    strategy_id=config.strategy_id,
                    strategy_version=config.version,
                    strategy_family=config.strategy_family,
                    ticker=ind.ticker,
                    signal_date=ind.bar_date,
                    action="EXIT_LONG",
                    reason=f"RSI Overbought target reached: RSI={ind.rsi_14:.1f} >= {rsi_exit}",
                    conviction_score=0.9,
                    atr_at_signal=atr,
                    close_at_signal=ind.close,
                )

        # 5. Maximum holding period time-stop (3-15 trading days swing horizon)
        if holding_days >= config.holding_period_max_days:
            return TradeSignal(
                strategy_id=config.strategy_id,
                strategy_version=config.version,
                strategy_family=config.strategy_family,
                ticker=ind.ticker,
                signal_date=ind.bar_date,
                action="EXIT_LONG",
                reason=f"Max swing holding period ({config.holding_period_max_days} trading days) reached",
                conviction_score=1.0,
                atr_at_signal=atr,
                close_at_signal=ind.close,
            )

        return None


