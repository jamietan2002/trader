class StrategyRegistry:
    """Persistent versioned Strategy Registry and Experiment Tracker.

    Guarantees:
    - Never overwrites a strategy version that is currently in PAPER_TRADING.
    - Tracks full experiment audit trail and status transitions.
    """

    def __init__(self, db: DatabaseManager) -> None:
        self.db = db

    def register_strategy(self, config: StrategyConfig) -> StrategyConfig:
        existing = self.get_strategy(config.strategy_id, config.version)
        if existing is not None:
            if existing.status == StrategyStatus.PAPER_TRADING.value:
                raise PermissionError(
                    f"Cannot overwrite strategy {config.strategy_id} v{config.version} because it is "
                    "currently active in PAPER_TRADING. Create a new version instead."
                )
        now_iso = utc_now_iso()
        self.db.execute(
            """
            INSERT INTO strategy_registry (
                strategy_id, version, name, strategy_family, status,
                hypothesis, observable_phenomenon, invalidation_conditions,
                target_market_regimes, holding_period_min_days, holding_period_max_days,
                universe_json, indicators_json, entry_rules_json, exit_rules_json,
                risk_params_json, backtest_summary_json, validation_summary_json,
                promotion_decision_reason, dataset_version, created_at, updated_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            ON CONFLICT(strategy_id, version) DO UPDATE SET
                name=excluded.name,
                status=excluded.status,
                hypothesis=excluded.hypothesis,
                entry_rules_json=excluded.entry_rules_json,
                exit_rules_json=excluded.exit_rules_json,
                risk_params_json=excluded.risk_params_json,
                backtest_summary_json=excluded.backtest_summary_json,
                validation_summary_json=excluded.validation_summary_json,
                promotion_decision_reason=excluded.promotion_decision_reason,
                dataset_version=excluded.dataset_version,
                updated_at=excluded.updated_at
            """,
            (
                config.strategy_id,
                config.version,
                config.name,
                config.strategy_family,
                config.status,
                config.hypothesis,
                config.observable_phenomenon,
                config.invalidation_conditions,
                json.dumps(config.target_market_regimes),
                config.holding_period_min_days,
                config.holding_period_max_days,
                json.dumps(config.universe),
                json.dumps(config.required_indicators),
                json.dumps(config.entry_rules),
                json.dumps(config.exit_rules),
                json.dumps(config.risk_params),
                json.dumps(config.backtest_summary) if config.backtest_summary else None,
                json.dumps(config.validation_summary) if config.validation_summary else None,
                config.promotion_decision_reason,
                config.dataset_version,
                config.created_at or now_iso,
                now_iso,
            ),
        )
        return self.get_strategy(config.strategy_id, config.version) or config

    def create_new_version(
        self,
        base_strategy_id: str,
        entry_rules_updates: Optional[Dict[str, Any]] = None,
        exit_rules_updates: Optional[Dict[str, Any]] = None,
        hypothesis_note: Optional[str] = None,
    ) -> StrategyConfig:
        """Create an incremented version of an existing strategy without mutating prior versions."""
        versions = self.list_strategies(strategy_id=base_strategy_id)
        if not versions:
            raise KeyError(f"Strategy {base_strategy_id} not found in registry")
        latest = max(versions, key=lambda s: s.version)
        new_entry = dict(latest.entry_rules)
        if entry_rules_updates:
            new_entry.update(entry_rules_updates)
        new_exit = dict(latest.exit_rules)
        if exit_rules_updates:
            new_exit.update(exit_rules_updates)
        new_cfg = StrategyConfig(
            strategy_id=latest.strategy_id,
            version=latest.version + 1,
            name=latest.name,
            strategy_family=latest.strategy_family,
            status=StrategyStatus.DRAFT.value,
            hypothesis=f"{latest.hypothesis} | v{latest.version + 1}: {hypothesis_note or 'Parameter refinement'}",
            observable_phenomenon=latest.observable_phenomenon,
            invalidation_conditions=latest.invalidation_conditions,
            target_market_regimes=latest.target_market_regimes,
            holding_period_min_days=latest.holding_period_min_days,
            holding_period_max_days=latest.holding_period_max_days,
            universe=latest.universe,
            required_indicators=latest.required_indicators,
            entry_rules=new_entry,
            exit_rules=new_exit,
            risk_params=latest.risk_params,
        )
        return self.register_strategy(new_cfg)

    def update_status(
        self,
        strategy_id: str,
        version: int,
        new_status: StrategyStatus,
        reason: str = "",
        backtest_summary: Optional[Dict[str, Any]] = None,
        validation_summary: Optional[Dict[str, Any]] = None,
        dataset_version: Optional[str] = None,
    ) -> StrategyConfig:
        existing = self.get_strategy(strategy_id, version)
        if existing is None:
            raise KeyError(f"Strategy {strategy_id} v{version} not found")
        now_iso = utc_now_iso()
        bt_json = (
            json.dumps(backtest_summary)
            if backtest_summary is not None
            else (json.dumps(existing.backtest_summary) if existing.backtest_summary else None)
        )
        val_json = (
            json.dumps(validation_summary)
            if validation_summary is not None
            else (json.dumps(existing.validation_summary) if existing.validation_summary else None)
        )
        self.db.execute(
            """
            UPDATE strategy_registry
            SET status = ?,
                promotion_decision_reason = ?,
                backtest_summary_json = ?,
                validation_summary_json = ?,
                dataset_version = COALESCE(?, dataset_version),
                updated_at = ?
            WHERE strategy_id = ? AND version = ?
            """,
            (
                new_status.value,
                reason or existing.promotion_decision_reason,
                bt_json,
                val_json,
                dataset_version,
                now_iso,
                strategy_id,
                version,
            ),
        )
        # Automatically retire older PAPER_TRADING versions of the same strategy_id when a newer version is promoted
        if new_status == StrategyStatus.PAPER_TRADING:
            self.db.execute(
                """
                UPDATE strategy_registry
                SET status = ?,
                    promotion_decision_reason = ?,
                    updated_at = ?
                WHERE strategy_id = ? AND version < ? AND status = ?
                """,
                (
                    StrategyStatus.RETIRED.value,
                    f"Superseded by promoted {strategy_id} v{version}.",
                    now_iso,
                    strategy_id,
                    version,
                    StrategyStatus.PAPER_TRADING.value,
                ),
            )
        updated = self.get_strategy(strategy_id, version)
        assert updated is not None
        return updated

    def record_experiment(
        self,
        experiment_id: str,
        strategy_id: str,
        version: int,
        experiment_type: str,
        dataset_version: str,
        start_date: str,
        end_date: str,
        parameters: Dict[str, Any],
        metrics: Dict[str, Any],
        equity_curve: List[Dict[str, Any]],
        trades: List[Dict[str, Any]],
        evaluation_report: Optional[Dict[str, Any]] = None,
        passed_promotion: bool = False,
    ) -> None:
        self.db.execute(
            """
            INSERT INTO strategy_experiments (
                experiment_id, strategy_id, version, experiment_type,
                dataset_version, start_date, end_date, parameters_json,
                metrics_json, equity_curve_json, trades_json,
                evaluation_report_json, passed_promotion, created_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            ON CONFLICT(experiment_id) DO UPDATE SET
                metrics_json=excluded.metrics_json,
                evaluation_report_json=excluded.evaluation_report_json,
                passed_promotion=excluded.passed_promotion
            """,
            (
                experiment_id,
                strategy_id,
                version,
                experiment_type,
                dataset_version,
                start_date,
                end_date,
                json.dumps(parameters),
                json.dumps(metrics),
                json.dumps(equity_curve),
                json.dumps(trades),
                json.dumps(evaluation_report) if evaluation_report else None,
                1 if passed_promotion else 0,
                utc_now_iso(),
            ),
        )

    def get_strategy(self, strategy_id: str, version: int) -> Optional[StrategyConfig]:
        row = self.db.fetch_one(
            "SELECT * FROM strategy_registry WHERE strategy_id = ? AND version = ?",
            (strategy_id, version),
        )
        return self._row_to_config(row) if row else None

    def list_strategies(
        self,
        strategy_id: Optional[str] = None,
        status: Optional[str] = None,
    ) -> List[StrategyConfig]:
        clauses: List[str] = []
        params: List[Any] = []
        if strategy_id:
            clauses.append("strategy_id = ?")
            params.append(strategy_id)
        if status:
            clauses.append("status = ?")
            params.append(status)
        where_sql = f"WHERE {' AND '.join(clauses)}" if clauses else ""
        rows = self.db.fetch_all(
            f"SELECT * FROM strategy_registry {where_sql} ORDER BY strategy_id ASC, version DESC",
            tuple(params),
        )
        return [self._row_to_config(r) for r in rows]

    def list_experiments(self, strategy_id: Optional[str] = None) -> List[Dict[str, Any]]:
        if strategy_id:
            rows = self.db.fetch_all(
                "SELECT * FROM strategy_experiments WHERE strategy_id = ? ORDER BY created_at DESC",
                (strategy_id,),
            )
        else:
            rows = self.db.fetch_all("SELECT * FROM strategy_experiments ORDER BY created_at DESC")
        out: List[Dict[str, Any]] = []
        for r in rows:
            item = dict(r)
            item["parameters"] = json.loads(r["parameters_json"])
            item["metrics"] = json.loads(r["metrics_json"])
            item["equity_curve"] = json.loads(r["equity_curve_json"])
            item["trades"] = json.loads(r["trades_json"])
            item["evaluation_report"] = (
                json.loads(r["evaluation_report_json"]) if r["evaluation_report_json"] else None
            )
            out.append(item)
        return out

    @staticmethod
    def _row_to_config(row: Dict[str, Any]) -> StrategyConfig:
        return StrategyConfig(
            strategy_id=row["strategy_id"],
            version=int(row["version"]),
            name=row["name"],
            strategy_family=row["strategy_family"],
            status=row["status"],
            hypothesis=row["hypothesis"],
            observable_phenomenon=row["observable_phenomenon"],
            invalidation_conditions=row["invalidation_conditions"],
            target_market_regimes=json.loads(row["target_market_regimes"]),
            holding_period_min_days=int(row["holding_period_min_days"]),
            holding_period_max_days=int(row["holding_period_max_days"]),
            universe=json.loads(row["universe_json"]),
            required_indicators=json.loads(row["indicators_json"]),
            entry_rules=json.loads(row["entry_rules_json"]),
            exit_rules=json.loads(row["exit_rules_json"]),
            risk_params=json.loads(row["risk_params_json"]),
            created_at=row["created_at"],
            updated_at=row["updated_at"],
            dataset_version=row["dataset_version"],
            backtest_summary=json.loads(row["backtest_summary_json"]) if row["backtest_summary_json"] else None,
            validation_summary=json.loads(row["validation_summary_json"]) if row["validation_summary_json"] else None,
            promotion_decision_reason=row["promotion_decision_reason"],
        )

